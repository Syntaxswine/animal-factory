// Finds where each flamethrower sprite's painted nozzle ends, so fired flame leaves the muzzle.
// Run after re-exporting flamethrower sprites: node tools/measure-flame-nozzles.mjs
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {decodePNG} from './png-rgba.mjs';
import {WEAPON_EXPANSION_FRAMES} from '../dist/tactics/weapon-expansion-frames.js';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const OUTPUT=path.join(root,'dist/tactics/flame-nozzles.js');
export const flamethrowerFrames=()=>WEAPON_EXPANSION_FRAMES.filter(frame=>frame.weapon==='flamethrower');
export const framePath=frame=>path.join(root,'dist',frame.src.replace('../',''));

// Every sprite faces right and the projector is its rightmost part. The tip is the rightmost column
// with at least three opaque pixels (ignores stray antialiasing). The barrel axis is a least-squares
// line through the centres of the opaque run followed leftward from the tip, skipping the flared
// muzzle and any samples swollen by a hand or fitting; the nozzle centre is that axis at the tip.
export function measureNozzle({width,height,pixels}){
 const opaque=(x,y)=>x>=0&&y>=0&&x<width&&y<height&&pixels[(y*width+x)*4+3]>=128;
 let tip=-1;
 for(let x=width-1;x>=0&&tip<0;x--){let count=0;for(let y=0;y<height;y++)if(opaque(x,y))count++;if(count>=3)tip=x;}
 if(tip<0)throw Error('No opaque nozzle column');
 const column=[];for(let y=0;y<height;y++)if(opaque(tip,y))column.push(y);
 const runAt=(x,centre)=>{
  let y=Math.round(centre);
  if(!opaque(x,y)){const near=[1,2,3,4].flatMap(d=>[y-d,y+d]).find(q=>opaque(x,q));if(near===undefined)return null;y=near;}
  let top=y,bottom=y;while(opaque(x,top-1))top--;while(opaque(x,bottom+1))bottom++;return [top,bottom];
 };
 const samples=[];let centre=(column[0]+column.at(-1))/2;
 for(let x=tip;x>=tip-44;x--){const run=runAt(x,centre);if(!run||run[1]-run[0]+1>24)break;centre=(run[0]+run[1])/2;samples.push({x,y:centre,length:run[1]-run[0]+1});}
 const barrel=samples.filter(q=>q.x<=tip-6),lengths=barrel.map(q=>q.length).sort((a,b)=>a-b),fit=barrel.filter(q=>q.length<=lengths[lengths.length>>1]+2);
 if(fit.length<8)throw Error('Barrel too short to measure');
 const mx=fit.reduce((a,q)=>a+q.x,0)/fit.length,my=fit.reduce((a,q)=>a+q.y,0)/fit.length;
 const sxx=fit.reduce((a,q)=>a+(q.x-mx)**2,0),slope=fit.reduce((a,q)=>a+(q.x-mx)*(q.y-my),0)/sxx;
 const round=v=>Math.round(v*10)/10;
 // x is the muzzle's end face; y is a pixel centre (+0.5); angle in degrees, negative raises the barrel.
 return [tip+1,round(my+slope*(tip-mx)+.5),round(Math.atan(slope)*180/Math.PI)];
}

export function measureAll(){
 return Object.fromEntries(flamethrowerFrames().map(frame=>[frame.src,measureNozzle(decodePNG(fs.readFileSync(framePath(frame))))]));
}

export function nozzleModule(table){
 const rows=Object.entries(table).map(([src,value])=>` ${JSON.stringify(src)}:${JSON.stringify(value)}`);
 return `// Generated by tools/measure-flame-nozzles.mjs from the flamethrower sprite PNGs. Do not hand-edit.\n// [x, y, angle]: the muzzle end face and barrel axis in sprite pixels; angle in degrees, negative raises the barrel.\nexport const FLAME_NOZZLES={\n${rows.join(',\n')}\n};\n`;
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const table=measureAll();
 fs.writeFileSync(OUTPUT,nozzleModule(table));
 console.log(`Measured ${Object.keys(table).length} flamethrower nozzles → ${path.relative(root,OUTPUT)}`);
}
