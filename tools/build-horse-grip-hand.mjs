import fs from 'node:fs';
import {createRequire} from 'node:module';
import {sculptSurface,blend,ellipsoid,tapered} from '../dist/tactics/grey-surface.js';
const MeshoptSimplifier=createRequire(import.meta.url)('./vendor/meshoptimizer/meshopt_simplifier.cjs');
await MeshoptSimplifier.ready;
// A localized closed glove for the overhand carry: +X runs through the handle.
// The four finger arcs and opposing thumb leave the handle channel open.
function field(x,y,z){
 let d=ellipsoid(x,y,z,[0,.036,.009],[.047,.016,.033]);
 d=blend(d,ellipsoid(x,y,z,[0,.046,.022],[.047,.023,.029]),.008);
 for(const [i,xx] of [-.033,-.011,.011,.033].entries()){
  const reach=i===0||i===3?.002:0;
  const path=[[xx,.029,-.009],[xx,.017,-.029+reach],[xx,-.008,-.029+reach],[xx,-.024,-.013],[xx,-.022,.008]];
  for(let k=1;k<path.length;k++)d=blend(d,tapered(x,y,z,path[k-1],path[k],.009,.008),.003);
 }
 const thumb=[[-.042,.037,.023],[-.054,.011,.030],[-.044,-.011,.031],[-.026,-.019,.025]];
 for(let k=1;k<thumb.length;k++)d=blend(d,tapered(x,y,z,thumb[k-1],thumb[k],.012,.009),.004);
 return d;
}
const g=sculptSurface(field,[-.074,-.045,-.046],[.074,.112,.103],.0038),p=g.attributes.position.array;
let [ix]=MeshoptSimplifier.simplify(new Uint32Array(g.index.array),p,3,900*3,.0015,['ErrorAbsolute']);
const [remap,count]=MeshoptSimplifier.compactMesh(ix),positions=new Float32Array(count*3),normals=new Float32Array(count*3);
for(let i=0;i<remap.length;i++)if(remap[i]!==0xffffffff){positions.set(p.subarray(i*3,i*3+3),remap[i]*3);normals.set(g.attributes.normal.array.subarray(i*3,i*3+3),remap[i]*3);}
const data={triangles:ix.length/3,position:Array.from(positions,v=>+v.toFixed(7)),normal:Array.from(normals,v=>+v.toFixed(6)),index:Array.from(ix)};
fs.writeFileSync(new URL('../dist/tactics/horse-grip-hand-data.js',import.meta.url),'// Generated by tools/build-horse-grip-hand.mjs. Weapon-local handle channel at the origin.\nexport default '+JSON.stringify(data)+';\n');
console.log('Overhand glove:',data.triangles,'triangles');
